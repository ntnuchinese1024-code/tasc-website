/**
 * 理事長底下六個工作小組，以及各組的「組織簡則」全文。
 *
 * 前五組的條文依 111 年 3 月 13 日理監事會議通過的 PDF 原文逐字轉錄；
 * 學術組是 115 年 10 月 11 日理監事會議新設，依當次通過的條文轉錄。
 * 原始檔放在 public/downloads/，頁面下方有下載連結可對照。
 * 原文的用字都保留，不要順稿。目前只動過兩處，都不影響條文內容：
 *   1. 原檔打成半形的冒號「:」改成全形「：」，純粹是中文排版的字寬問題。
 *   2. 推廣課程組第一條的組名誤植，見該條的註解。
 * 條文實質內容如果要修改，請先回到理監事會走修正程序，改完再更新這裡跟 PDF。
 *
 * 條文結構只有三層：
 *   lead（條文本體）→ items（一、二、三…）→ tail（條列之後的補充段落）
 * 三個欄位都是選填，實際有什麼就填什麼。
 */

export interface CharterArticle {
  /** 條號，例如「第一條」 */
  num: string;
  /** 條文本體，條列之前的段落 */
  lead?: string;
  /** 一、二、三… 編號條列 */
  items?: string[];
  /** 條列之後的補充段落 */
  tail?: string[];
}

/** 頁面上方的「重點速覽」三格，內容都是從條文裡摘出來的 */
export interface GroupFact {
  label: string;
  value: string;
}

/**
 * 小組正在辦或準備要辦的計畫（目前只有學術組在用）。
 * 計畫原始檔同樣放在 public/downloads/；內容依計畫書原文整理，不要自行增補時間或人數。
 */
export interface GroupPlan {
  /** 頁內錨點，例如 /about/groups/academic#hunt */
  id: string;
  /** 活動類型標籤，例如「線上讀書會」 */
  kind: string;
  /** 目前狀態，例如「招募中」「籌備中」 */
  status: string;
  title: string;
  /** 段落，依計畫書原文 */
  intro: string[];
  facts: GroupFact[];
  pdf?: { file: string; size: string; name: string };
  /**
   * 報名系統裡這個活動的 slug。報名系統開放報名時，頁面才會出現「前往報名」按鈕，
   * 連到 /news/upcoming/<slug>/；還沒上架或已截止就不顯示，免得連到不存在的頁面。
   */
  signupSlug?: string;
}

export interface WorkingGroup {
  slug: string;
  /** 網站上的簡稱，也是組織架構圖上的節點名稱 */
  name: string;
  /** 一句話說明這個小組在做什麼 */
  summary: string;
  /** 主色，取自標誌色票（見 global.css） */
  color: "magenta" | "blue" | "red" | "green" | "orange";
  /** 簡則的正式全名，跟 PDF 標題一致 */
  docTitle: string;
  /** 通過日期 */
  approved: string;
  facts: GroupFact[];
  /** 原始 PDF 在 public/downloads/ 底下的檔名 */
  pdf: { file: string; size: string };
  articles: CharterArticle[];
  /** 小組的計畫，沒有就不顯示整個區塊 */
  plans?: GroupPlan[];
}

