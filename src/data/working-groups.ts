/** 中文數字，條列用「一、二、三…」而不是 1. 2. 3. */
const cn = ["一", "二", "三", "四", "五", "六", "七", "八", "九", "十"];

export function cnIndex(i: number): string {
  return cn[i] ?? String(i + 1);
}
